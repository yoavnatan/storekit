/**
 * The help centre's corpus. Data only — the lookups are `help.ts`, and the rule about what an
 * article may claim is on that file's header. Read it before adding one.
 *
 * ── Three rules this table is written under ──
 * **Only what works today.** An article about an unbuilt feature turns the surface built to reduce
 * support contact into the thing generating it, and on a platform running ONE Merchant Center
 * account for every seller it is also the "misrepresentation" class that suspends everybody's ads
 * at once. Where an article describes a decided MODEL rather than a working screen — how a seller's
 * money reaches him — it says the model and never a date.
 *
 * **Name the door.** Every step names the screen and the button a seller would actually press
 * (memory `feedback_entry_point_names_the_action`). "ייבוא/ייצוא CSV" once hid a whole built
 * feature from the person it was built for; an article that says "אפשר לייבא" and not *where*
 * repeats that failure in a longer form.
 *
 * **No numbers typed here.** Prices, percentages and statutory windows live in the modules that own
 * them (`pricing.ts`, `returns.ts`) and articles link to `/pricing` or `/returns-policy` instead of
 * restating a figure that will drift. The one exception is a figure that IS the article — and there
 * are none in the table today.
 *
 * Hebrew in both UI languages, the same standard `terms.astro`, `contact.astro` and
 * `returns-policy.astro` set: a machine-translated support page reads as a shell, and this is an
 * Israel-facing product.
 */

export type HelpGroupId = 'start' | 'catalog' | 'orders' | 'money' | 'growth';

export interface HelpArticle {
  /** URL segment. Latin, stable — it is linked from the dashboard and will be linked from outside. */
  slug: string;
  group: HelpGroupId;
  title: string;
  /** One line, shown on the index and used as the page description. It is what a seller scans, so
   *  it answers the question rather than announcing the topic. */
  summary: string;
  /** Paragraphs. Rendered in order, one `<p>` each — no markup, no lists, deliberately: an article
   *  a seller reads on a phone between two customers is three short paragraphs, not a manual. */
  body: string[];
  /** Slugs of articles worth reading next. Verified by `tests/help-articles.test.ts`. */
  related?: string[];
}

